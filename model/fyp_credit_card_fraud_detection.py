# 5.3  Deep Autoencoder
# How it works: trained to reconstruct NORMAL transactions.
# Fraud patterns are unlike training data → high reconstruction error = anomaly.
# Architecture: 64 → 32 → 16 (bottleneck) → 32 → 64

print("Building Deep Autoencoder...")

INPUT_DIM = X_train.shape[1]

def build_autoencoder(input_dim):
    inp = keras.Input(shape=(input_dim,))
    x = layers.Dense(64, activation='relu',
                     kernel_regularizer=regularizers.l2(1e-4))(inp)
    x = layers.BatchNormalization()(x)
    x = layers.Dropout(0.2)(x)
    x = layers.Dense(32, activation='relu')(x)
    x = layers.BatchNormalization()(x)
    x = layers.Dense(16, activation='relu', name='bottleneck')(x)
    x = layers.Dense(32, activation='relu')(x)
    x = layers.BatchNormalization()(x)
    x = layers.Dense(64, activation='relu')(x)
    x = layers.Dropout(0.2)(x)
    out = layers.Dense(input_dim, activation='linear')(x)
    model = keras.Model(inputs=inp, outputs=out)
    model.compile(optimizer=keras.optimizers.Adam(1e-3), loss='mse')
    return model

