def predict_transaction(raw_features_dict):
    """
    Predict fraud for a single raw transaction.
    Input  : dict with keys matching df columns (V1-V28, Time, Amount)
    Output : dict with prediction, confidence, and anomaly scores
    """
    row = pd.DataFrame([raw_features_dict])

    # In the original feature engineering (cell wy5Qva9zgW0f),
    # the 'Time' column was not found in the dataset,
    # and thus 'Hour' and 'Is_night' features were not created.
    # We skip these features here to maintain consistency with the trained model.

    # Amount features
    if 'Amount' in row.columns:
        row['Amount_log']   = np.log1p(row['Amount'])
        row['Amount_sqrt']  = np.sqrt(row['Amount'])
        row['High_amount']  = (row['Amount'] > df['Amount'].quantile(0.95)).astype(int)
        row['Zero_amount']  = (row['Amount'] == 0).astype(int)
        row['Amount_x_V14'] = row['Amount_log'] * row['V14'].abs()

    # Interaction features
    row['V14_x_V12'] = row['V14'] * row['V12']
    row['V14_x_V17'] = row['V14'] * row['V17']
    row['V4_x_V11']  = row['V4']  * row['V11']

    # Drop original 'Time' and 'Amount' columns, if they exist.
    # 'Time' is not expected to be in `row` based on the input `df`.
    # 'Amount' was processed into derived features and should be dropped.
    cols_to_drop_final = [c for c in ['Time', 'Amount'] if c in row.columns]
    if cols_to_drop_final:
        row = row.drop(columns=cols_to_drop_final)

    # Ensure the order and presence of columns match `X.columns` before scaling
    # This is crucial to avoid errors in the scaler and model predictions.
    # We select columns from `row` that are present in `X.columns` to ensure alignment.
    # This implicitly handles cases where 'Hour'/'Is_night' would be missing from row if Time was not input.
    row_aligned = row[X.columns]
    row_scaled = pd.DataFrame(scaler.transform(row_aligned), columns=X.columns)

    iso_s = minmax(
    -iso.score_samples(row_scaled),
    iso_score_train
    ).item()

    svm_s = minmax(
    -ocsvm.score_samples(nystroem.transform(row_scaled)),
    svm_score_train
    ).item()

    ae_s = minmax(
    reconstruction_error(autoencoder, row_scaled),
    ae_score_train
    ).item()

    row_aug = augment(row_scaled,
                      np.array([iso_s]), np.array([svm_s]), np.array([ae_s]))

    prob  = best_model.predict_proba(row_aug)[0][1]
    label = '🚨 FRAUD' if prob >= best_thresh_t else '✅ LEGITIMATE'

    return {
        'prediction': label,
        'confidence': round(float(prob), 4),
        'iso_score' : round(iso_s, 4),
        'svm_score' : round(svm_s, 4),
        'ae_error'  : round(ae_s, 4),
        'threshold' : round(best_thresh_t, 3),
    }


