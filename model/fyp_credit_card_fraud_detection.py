"""---
## 🔗 STEP 6 — Feature Augmentation (Score Fusion)

**This is what makes the Hybrid Model:**  
1. Min-max normalise all three anomaly scores to [0, 1]  
2. Create 8 derived score features (avg, max, interactions)  
3. Append them to original features  
4. Final classifier sees both raw transaction data AND anomaly intelligence
"""

# 6.1  Min-max normalise scores using training stats only
def minmax(scores, ref_scores):
    mn, mx = ref_scores.min(), ref_scores.max()
    return np.clip((scores - mn) / (mx - mn + 1e-8), 0, 1)

iso_n_train = minmax(iso_score_train, iso_score_train)
svm_n_train = minmax(svm_score_train, svm_score_train)
ae_n_train  = minmax(ae_score_train,  ae_score_train)

iso_n_test  = minmax(iso_score_test, iso_score_train)
svm_n_test  = minmax(svm_score_test, svm_score_train)
ae_n_test   = minmax(ae_score_test,  ae_score_train)

print("Anomaly scores normalised to [0, 1] (using training stats only).")

# 6.2  Build augmented feature matrices
def augment(X_df, iso_n, svm_n, ae_n):
    avg = (iso_n + svm_n + ae_n) / 3.0
    mx  = np.maximum.reduce([iso_n, svm_n, ae_n])
    df_aug = X_df.copy()
    df_aug['score_iso'] = iso_n
    df_aug['score_svm'] = svm_n
    df_aug['score_ae']  = ae_n
    df_aug['score_avg'] = avg
    df_aug['score_max'] = mx
    df_aug['iso_x_ae']  = iso_n * ae_n
    df_aug['iso_x_svm'] = iso_n * svm_n
    df_aug['svm_x_ae']  = svm_n * ae_n
    return df_aug

X_train_aug = augment(X_train, iso_n_train, svm_n_train, ae_n_train)
